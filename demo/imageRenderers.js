import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import { createElement } from 'react'

const require = createRequire(import.meta.url)
const interRegular = readFileSync(
  require.resolve('@fontsource/inter/files/inter-latin-400-normal.woff'),
)
const interBold = readFileSync(
  require.resolve('@fontsource/inter/files/inter-latin-700-normal.woff'),
)
function loadBackground(filename, mimeType) {
  const data = readFileSync(new URL(`./static/img/${filename}`, import.meta.url))
  return `data:${mimeType};base64,${data.toString('base64')}`
}

const backgrounds = {
  png: loadBackground('og-background.png', 'image/png'),
  svg: loadBackground('og-background.svg', 'image/svg+xml'),
}

const imageOptions = {
  width: 1200,
  height: 630,
  fonts: [
    { name: 'Inter', data: interRegular, weight: 400, style: 'normal' },
    { name: 'Inter', data: interBold, weight: 700, style: 'normal' },
  ],
}

function renderImage(label, title, description, background = backgrounds.png) {
  return [
    createElement(
      'div',
      {
        style: {
          position: 'relative',
          alignItems: 'flex-start',
          backgroundColor: '#263141',
          color: '#fcfcfc',
          display: 'flex',
          flexDirection: 'column',
          height: '100%',
          justifyContent: 'center',
          padding: 72,
          width: '100%',
        },
      },
      createElement('img', {
        src: background,
        alt: '',
        style: {
          position: 'absolute',
          top: 0,
          left: 0,
          width: '100%',
          height: '100%',
          objectFit: 'cover',
        },
      }),
      createElement(
        'div',
        {
          style: {
            position: 'relative',
            color: '#f2bab6',
            fontSize: 24,
            fontWeight: 700,
            marginBottom: 24,
          },
        },
        label,
      ),
      createElement(
        'div',
        {
          style: {
            position: 'relative',
            fontSize: 64,
            fontWeight: 700,
            lineHeight: 1.1,
            marginBottom: 24,
          },
        },
        title,
      ),
      createElement(
        'div',
        {
          style: {
            position: 'relative',
            color: '#d1d5db',
            fontSize: 28,
            lineHeight: 1.35,
          },
        },
        description || 'Generated by @homotechsual/docusaurus-og',
      ),
    ),
    imageOptions,
  ]
}

export const docs = (data) =>
  renderImage(
    'DOCUMENTATION',
    data.metadata.title,
    data.metadata.description,
    data.metadata.frontMatter?.og_background === 'svg'
      ? backgrounds.svg
      : backgrounds.png,
  )

export const blog = (data) => {
  const title =
    data.data?.metadata?.title ??
    (data.pageType === 'archive' ? 'Blog archive' : 'Blog')

  return renderImage('BLOG', title, data.data?.metadata?.description)
}

export const pages = (data) =>
  renderImage('PAGE', data.metadata.title, data.metadata.description)
